#!/usr/bin/env python3
import os
import sys

# /opt/copy.py is a pipeline module and shadows the Python stdlib "copy".
# tarfile needs the stdlib implementation: cache it before importing tarfile.
MODULE_DIR = os.path.dirname(os.path.abspath(__file__))
module_dir_real = os.path.realpath(MODULE_DIR)
sys.path[:] = [
    path for path in sys.path
    if os.path.realpath(path or os.getcwd()) != module_dir_real
]
import copy as _stdlib_copy  # noqa: F401
import tarfile
import tempfile
import configparser
import csv
import glob
import re
import shutil
import subprocess
from pathlib import Path

sys.path.insert(0, MODULE_DIR)
from pymodule_common import load_config, record_version, update_run_summary

sppider_seq_autop2_version = "2.0.0"
sppider_seq_docker_version = "2026-05"
sppider_seq_program_version = "unknown"
sppider_seq_ref = ""
sppider_seq_doi = ""


def _safe_label(value):
    """Use a stable output label without filesystem-special characters."""
    return re.sub(r"[^a-zA-Z0-9_.-]", "_", value).strip("._") or "sequence"


def _read_input_config(input_path):
    """Read a module-specific config, either [Inputs] INI or bare key=value."""
    path = os.path.join(input_path, "config")
    if not os.path.isfile(path):
        # Backwards compatibility with existing protocols.
        return None
    with open(path, encoding="utf-8") as handle:
        data = handle.read().strip()
    if not data:
        sys.exit(f"Error: SPPIDER-seq config is empty: {path}")
    parser = configparser.ConfigParser(interpolation=None)
    parser.optionxform = str
    if not re.search(r"(?m)^\s*\[", data):
        data = "[Inputs]\n" + data
    try:
        parser.read_string(data)
    except configparser.Error as exc:
        sys.exit(f"Error: invalid SPPIDER-seq config {path}: {exc}")
    if not parser.has_section("Inputs"):
        sys.exit("Error: SPPIDER-seq input/config must contain [Inputs]")
    query = parser.get("Inputs", "query", fallback="").strip()
    partners = parser.get("Inputs", "partners", fallback="").strip()
    if not query or not partners:
        sys.exit("Error: SPPIDER-seq input/config requires query and partners")
    return query, partners


def _resolve_fasta(value, input_path, project):
    """Resolve logical list aliases or a path to an existing FASTA file.

    The aliases refer to the two multi-FASTA files previously generated by
    the separate pdb2fasta steps, NOT to the PDB list text itself.
    """
    aliases = {
        "receptors_list": ("FASTA/Receptors/Fasta_file", "receptors", "receptors_list.txt"),
        "receptor_list": ("FASTA/Receptors/Fasta_file", "receptors", "receptors_list.txt"),
        "ligands_list": ("FASTA/Ligands/Fasta_file", "ligands", "ligands_list.txt"),
        "ligand_list": ("FASTA/Ligands/Fasta_file", "ligands", "ligands_list.txt"),
    }
    if value in aliases:
        suffix, label, list_file = aliases[value]
        list_path = f"/data/{project}/PDBs/{list_file}"
        if not os.path.isfile(list_path):
            sys.exit(f"Error: list for {value} was not created by copy: {list_path}")
        path = f"/data/{project}/{suffix}"
    else:
        # A direct path is relative to the project by default; both /data/X
        # and paths relative to the module config directory are accepted.
        candidates = (
            [value] if os.path.isabs(value) else [
                f"/data/{project}/{value}", f"/data/{value}",
                os.path.join(input_path, value),
            ]
        )
        path = next((p for p in candidates if os.path.isfile(p)), candidates[0])
        label = os.path.splitext(os.path.basename(path))[0]
        if label == "Fasta_file":
            label = os.path.basename(os.path.dirname(path))
    path = os.path.realpath(path)
    data_root = os.path.realpath("/data")
    if os.path.commonpath([data_root, path]) != data_root:
        sys.exit(f"Error: SPPIDER-seq FASTA must be located under /data: {path}")
    if not os.path.isfile(path) or os.path.getsize(path) == 0:
        sys.exit(f"Error: FASTA file does not exist or is empty: {path}")
    return path, _safe_label(label.lower())


def _actual_pairs(csv_path, fallback_query, fallback_partner):
    """List individual protein pairs from the generated residue-level CSV."""
    if os.path.isfile(csv_path):
        with open(csv_path, newline="", encoding="utf-8") as handle:
            reader = csv.DictReader(handle, delimiter=";")
            if reader.fieldnames and {"query_id", "partner_id"}.issubset(reader.fieldnames):
                pairs = {(row["query_id"], row["partner_id"])
                         for row in reader if row["query_id"] and row["partner_id"]}
                if pairs:
                    return sorted(pairs)
    return [(fallback_query, fallback_partner)]


def main():
    global sppider_seq_autop2_version, sppider_seq_docker_version, sppider_seq_ref, sppider_seq_doi

    if len(sys.argv) < 4:
        sys.exit(
            "Usage: sppider_seq.py "
            "<input_dir> <output_dir> <prefix>"
        )

    input_dir, output_dir, prefix = (
        sys.argv[1],
        sys.argv[2],
        sys.argv[3],
    )

    load_config()

    if os.environ.get(
        "sppider_seq_docker_c_version"
    ):
        sppider_seq_autop2_version = "?"
        sppider_seq_docker_version = os.environ[
            "sppider_seq_docker_c_version"
        ]
        sppider_seq_ref = "?"
        sppider_seq_doi = "?"

    scrambles = os.environ.get(
        "sppider_seq_scrambles",
        "0"
    )

    project = os.environ.get("project", "")

    input_path = f"/data/{input_dir}"
    output_path = f"/data/{output_dir}"
    intermediate_path = (
        f"/data/{prefix}sppider_seq"
    )

    if not os.path.isdir(input_path):
        sys.exit(
            f"Error: input directory does not exist:\n"
            f"{input_path}"
        )

    os.makedirs(
        output_path,
        exist_ok=True
    )

    os.makedirs(
        intermediate_path,
        exist_ok=True
    )
    archive_root = os.path.join(intermediate_path, "sppider_seq")
    os.makedirs(archive_root, exist_ok=True)


    if not project:
        sys.exit("Error: /data/config requires project")

    module_settings = _read_input_config(input_path)
    if module_settings is not None:
        query_ref, partners_ref = module_settings
        query_path, query_label = _resolve_fasta(query_ref, input_path, project)
        partner_files = [_resolve_fasta(ref, input_path, project)
                         for ref in partners_ref.split()]
    else:
        # Legacy config: the FASTA files were placed directly in input_path.
        legacy_query = os.environ.get("sppider_seq_query", "").strip()
        if not legacy_query:
            sys.exit("Error: add an input/config with [Inputs], query and partners")
        query_path, query_label = _resolve_fasta(legacy_query, input_path, project)
        legacy_partners = os.environ.get("sppider_seq_partners", "").strip()
        if legacy_partners:
            partner_files = [_resolve_fasta(ref, input_path, project)
                             for ref in legacy_partners.split()]
        else:
            query_basename = os.path.basename(query_path)
            partner_files = [
                (path, _safe_label(os.path.splitext(os.path.basename(path))[0]))
                for pattern in ("*.fa", "*.faa", "*.fasta", "*.fas")
                for path in sorted(glob.glob(os.path.join(input_path, pattern)))
                if os.path.basename(path) != query_basename
            ]
    if not partner_files:
        sys.exit("Error: SPPIDER-seq has no partner sequences")

    summary_file = os.path.join(
        output_path,
        "sppider_seq_runs.csv"
    )


    for pair_idx, (partner_path, partner_label) in enumerate(partner_files, 1):
        # Both pdb2fasta outputs are literally named 'Fasta_file'. Rename
        # *copies* inside the work directory to avoid one overwriting the other.
        query_name = f"{query_label}.fasta"
        partner_name = f"{partner_label}.fasta"
        if query_name == partner_name:
            partner_name = f"{partner_label}_partner.fasta"
        # Keep folder names neutral: actual query and partner IDs are in the CSV.
        pair_name = f"prediction_{pair_idx:02d}"

        pair_intermediate_dir = os.path.join(
            intermediate_path,
            "sppider_seq",
            pair_name
        )

        pair_work_dir = os.path.join(
            pair_intermediate_dir,
            "work"
        )

        pair_output_dir = os.path.join(
            pair_work_dir,
            "output"
        )

        final_pair_output_dir = os.path.join(
            output_path,
            pair_name
        )

        os.makedirs(
            pair_work_dir,
            exist_ok=True
        )

        if os.path.isdir(pair_output_dir):
            shutil.rmtree(pair_output_dir)
        os.makedirs(
            pair_output_dir,
            exist_ok=True
        )

        os.makedirs(
            final_pair_output_dir,
            exist_ok=True
        )

        shutil.copy2(
            query_path,
            os.path.join(
                pair_work_dir,
                query_name
            )
        )

        shutil.copy2(
            partner_path,
            os.path.join(
                pair_work_dir,
                partner_name
            )
        )

        # The Docker daemon runs on the host, so a nested -v mount cannot
        # reliably refer to /data paths inside this auto-p2docking container.
        # Transport the FASTA inputs and the output through Docker stdin/stdout
        # rather than adding host-path settings or changing docker run.
        shell_script = (
            'set -eu; '
            'mkdir -p /tmp/sppider_work; '
            'tar -xf - -C /tmp/sppider_work; '
            'python3 /usr/local/bin/run_sppider_seq.py '
            f'--query /tmp/sppider_work/{query_name} '
            f'--partner /tmp/sppider_work/{partner_name} '
            '--output /tmp/sppider_work/output '
            f'--scrambles {scrambles} '
            '> /tmp/sppider_work/sppider.log 2>&1 '
            '|| { cat /tmp/sppider_work/sppider.log >&2; exit 1; }; '
            'tar -cf - -C /tmp/sppider_work output'
        )
        print(f'SPPIDER-seq: running prediction {pair_idx}/{len(partner_files)}...', flush=True)
        docker_cmd = [
            'docker', 'run', '--rm', '-i', '--entrypoint', '/bin/sh',
            f'pegi3s/sppider-seq:{sppider_seq_docker_version}',
            '-c', shell_script,
        ]
        # Silence verbose model logs on success; print them on failure. Stdout is binary TAR.
        with tempfile.TemporaryFile() as input_tar, tempfile.TemporaryFile() as output_tar:
            with tarfile.open(fileobj=input_tar, mode='w') as archive:
                archive.add(os.path.join(pair_work_dir, query_name),
                            arcname=query_name, recursive=False)
                archive.add(os.path.join(pair_work_dir, partner_name),
                            arcname=partner_name, recursive=False)
            input_tar.seek(0)
            try:
                result = subprocess.run(
                    docker_cmd, stdin=input_tar, stdout=output_tar, check=False,
                )
            except OSError as exc:
                sys.exit(f'Error: could not start SPPIDER-seq Docker: {exc}')

            if result.returncode != 0:
                sys.exit(
                    f'Error: SPPIDER-seq failed with exit code {result.returncode}'
                )

            output_tar.seek(0)
            try:
                with tarfile.open(fileobj=output_tar, mode='r:*') as archive:
                    members = archive.getmembers()
                    if not members:
                        sys.exit('Error: SPPIDER-seq returned an empty output archive')
                    if any(
                        Path(member.name).is_absolute()
                        or '..' in Path(member.name).parts
                        or member.issym() or member.islnk() or member.isdev()
                        for member in members
                    ):
                        sys.exit('Error: unsafe path in SPPIDER-seq output archive')
                    archive.extractall(path=pair_work_dir, filter='data')
            except (tarfile.TarError, OSError) as exc:
                sys.exit(f'Error: could not read SPPIDER-seq output: {exc}')

        if not os.listdir(
            pair_output_dir
        ):
            sys.exit(
                f"Error: SPPIDER-seq produced no output "
                f"for pair:\n"
                f"{pair_name}"
            )

        raw_output_dir = pair_output_dir

        # Preserve the original public output contents for the pair.
        for entry in sorted(os.listdir(pair_output_dir)):
            source = os.path.join(pair_output_dir, entry)
            target = os.path.join(final_pair_output_dir, entry)
            if os.path.isdir(source):
                shutil.copytree(source, target, dirs_exist_ok=True)
            else:
                shutil.copy2(source, target)

        renamed_csv = os.path.join(
            final_pair_output_dir,
            f"{pair_name}.sppider."
            f"interface_residues.csv"
        )

        plain_interface_csv = os.path.join(
            final_pair_output_dir,
            "interface_residues.csv"
        )

        if os.path.isfile(
            plain_interface_csv
        ):
            shutil.copy2(
                plain_interface_csv,
                renamed_csv
            )

        else:
            print(
                f"Warning: interface_residues.csv "
                f"not found for {pair_name}"
            )

        if os.path.isfile(renamed_csv):
            shutil.copy2(renamed_csv, os.path.join(pair_intermediate_dir, os.path.basename(renamed_csv)))

        # A multi-FASTA represents several PDBs. Preserve the real protein
        # IDs instead of summarising everything as one 'Fasta_file' pair.
        for query_id, partner_id in _actual_pairs(
            plain_interface_csv, query_label, partner_label
        ):
            update_run_summary(
                summary_file,
                ["query", "partner", "output_directory", "interface_residues_csv",
                 "raw_output_directory"],
                ["query", "partner"],
                {"query": query_id, "partner": partner_id,
                 "output_directory": final_pair_output_dir,
                 "interface_residues_csv": renamed_csv,
                 "raw_output_directory": raw_output_dir},
            )

    shutil.copy2(summary_file, os.path.join(archive_root, os.path.basename(summary_file)))

    record_version(
        f'sppider_seq {sppider_seq_autop2_version},'
        f'pegi3s/sppider-seq:{sppider_seq_docker_version},'
        f'SPPIDER-seq {sppider_seq_program_version},'
        f'"{sppider_seq_ref}","{sppider_seq_doi}"'
    )


if __name__ == "__main__":
    print(
        "Running: SPPIDER-seq",
        flush=True
    )

    main()
